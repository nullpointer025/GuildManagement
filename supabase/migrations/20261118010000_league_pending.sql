-- Battle-record rows of players who weren't in the roster yet when the league was
-- uploaded (e.g. new members). They're kept here and moved into guild_league_stats
-- automatically once a roster import brings in a player they match.
--
-- Run once in the Supabase SQL editor after 20261118000000_league_fields.sql.
CREATE TABLE IF NOT EXISTS guild_league_pending (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  league_id BIGINT NOT NULL REFERENCES guild_leagues(id) ON DELETE CASCADE,
  ign TEXT NOT NULL,
  job TEXT,
  kills BIGINT,
  assists BIGINT,
  player_damage BIGINT,
  building_damage BIGINT,
  heal BIGINT,
  endure BIGINT,
  deaths BIGINT,
  revives BIGINT,
  monsters BIGINT,
  flag_repairs BIGINT,
  boss_kills BIGINT,
  boss_damage BIGINT,
  UNIQUE (league_id, ign)
);

CREATE INDEX IF NOT EXISTS idx_guild_league_pending_league ON guild_league_pending(league_id);

ALTER TABLE guild_league_pending ENABLE ROW LEVEL SECURITY;
