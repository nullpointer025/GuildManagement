-- Multi-guild: every invite code opens its own guild with its own roster, raids,
-- perma parties and league history.
--
-- Run once in the Supabase SQL editor after 20261025000000_init.sql.
-- If the database already holds data, it is moved into a first guild whose invite
-- code is set below. EDIT 'CHANGE-ME' to your current GUILD_INVITE_CODE before
-- running, so officers keep using the same code (it can also be changed later
-- from the /admin page).

CREATE TABLE IF NOT EXISTS guilds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  -- The code officers type on the gate page. It is what picks the guild.
  invite_code TEXT UNIQUE NOT NULL,
  -- Server ID for "Sync with Discord" (the shared bot must be invited to it).
  discord_guild_id TEXT,
  -- Bumped whenever the invite code changes, which signs everyone out of that guild.
  session_version INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT now_text(),
  updated_at TEXT NOT NULL DEFAULT now_text()
);

ALTER TABLE guilds ENABLE ROW LEVEL SECURITY;

-- Discord sync is opt-in per guild: officers turn it on in Guild settings and then
-- enter their server ID. Turning it off keeps the ID for next time.
ALTER TABLE guilds ADD COLUMN IF NOT EXISTS discord_sync_enabled BOOLEAN NOT NULL DEFAULT false;

-- Top-level tables get a guild_id. Their child tables (raid_slots, raid_parties,
-- perma_party_members, guild_league_stats) belong to a guild through their parent.
ALTER TABLE players ADD COLUMN IF NOT EXISTS guild_id BIGINT REFERENCES guilds(id) ON DELETE CASCADE;
ALTER TABLE raids ADD COLUMN IF NOT EXISTS guild_id BIGINT REFERENCES guilds(id) ON DELETE CASCADE;
ALTER TABLE perma_parties ADD COLUMN IF NOT EXISTS guild_id BIGINT REFERENCES guilds(id) ON DELETE CASCADE;
ALTER TABLE guild_leagues ADD COLUMN IF NOT EXISTS guild_id BIGINT REFERENCES guilds(id) ON DELETE CASCADE;

DO $$
DECLARE
  gid BIGINT;
BEGIN
  IF EXISTS (SELECT 1 FROM players WHERE guild_id IS NULL)
     OR EXISTS (SELECT 1 FROM raids WHERE guild_id IS NULL)
     OR EXISTS (SELECT 1 FROM perma_parties WHERE guild_id IS NULL)
     OR EXISTS (SELECT 1 FROM guild_leagues WHERE guild_id IS NULL) THEN
    INSERT INTO guilds (name, invite_code) VALUES ('My Guild', 'CHANGE-ME') RETURNING id INTO gid;
    UPDATE players SET guild_id = gid WHERE guild_id IS NULL;
    UPDATE raids SET guild_id = gid WHERE guild_id IS NULL;
    UPDATE perma_parties SET guild_id = gid WHERE guild_id IS NULL;
    UPDATE guild_leagues SET guild_id = gid WHERE guild_id IS NULL;
  END IF;
END $$;

ALTER TABLE players ALTER COLUMN guild_id SET NOT NULL;
ALTER TABLE raids ALTER COLUMN guild_id SET NOT NULL;
ALTER TABLE perma_parties ALTER COLUMN guild_id SET NOT NULL;
ALTER TABLE guild_leagues ALTER COLUMN guild_id SET NOT NULL;

-- An IGN is unique within a guild, not across all of them.
ALTER TABLE players DROP CONSTRAINT IF EXISTS players_ign_key;
ALTER TABLE players DROP CONSTRAINT IF EXISTS players_guild_ign_key;
ALTER TABLE players ADD CONSTRAINT players_guild_ign_key UNIQUE (guild_id, ign);

CREATE INDEX IF NOT EXISTS idx_raids_guild ON raids(guild_id);
CREATE INDEX IF NOT EXISTS idx_perma_parties_guild ON perma_parties(guild_id);
CREATE INDEX IF NOT EXISTS idx_guild_leagues_guild ON guild_leagues(guild_id);
