-- Guild Management schema (ported from the original SQLite database).
-- Timestamps stay TEXT in SQLite's "YYYY-MM-DD HH:MM:SS" UTC format so existing
-- data imports unchanged and the client sees the same values as before.

CREATE OR REPLACE FUNCTION now_text() RETURNS text
LANGUAGE sql STABLE AS $$
  SELECT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
$$;

CREATE TABLE IF NOT EXISTS players (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ign TEXT UNIQUE NOT NULL,
  level BIGINT,
  class TEXT,
  title TEXT,
  gender TEXT,
  position TEXT,
  gear_score BIGINT,
  weekly BIGINT,
  weekly_contribution BIGINT,
  total_contribution BIGINT,
  online_status TEXT,
  active INTEGER NOT NULL DEFAULT 1,
  in_discord INTEGER NOT NULL DEFAULT 0,
  ultimate INTEGER NOT NULL DEFAULT 0,
  last_imported_at TEXT,
  created_at TEXT NOT NULL DEFAULT now_text(),
  updated_at TEXT NOT NULL DEFAULT now_text()
);

CREATE TABLE IF NOT EXISTS raids (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  type TEXT NOT NULL DEFAULT 'guild_league',
  notes TEXT,
  notes_updated_at TEXT,
  created_at TEXT NOT NULL DEFAULT now_text(),
  updated_at TEXT NOT NULL DEFAULT now_text()
);

-- "board" splits each raid into independent party grids — 'main'/'sub' for a Guild
-- League raid, 'star'/'normal1'..'normal4' for a Polarity Zone raid — that share the
-- same roster pool but hold separate, independently-sized rosters. A board's party
-- count is however many party_index values exist for it in raid_parties.
CREATE TABLE IF NOT EXISTS raid_slots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raid_id BIGINT NOT NULL REFERENCES raids(id) ON DELETE CASCADE,
  board TEXT NOT NULL DEFAULT 'main',
  party_index INTEGER NOT NULL,
  slot_index INTEGER NOT NULL,
  player_id BIGINT REFERENCES players(id) ON DELETE SET NULL,
  UNIQUE (raid_id, board, party_index, slot_index)
);

CREATE INDEX IF NOT EXISTS idx_raid_slots_raid ON raid_slots(raid_id);

CREATE TABLE IF NOT EXISTS raid_parties (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raid_id BIGINT NOT NULL REFERENCES raids(id) ON DELETE CASCADE,
  board TEXT NOT NULL DEFAULT 'main',
  party_index INTEGER NOT NULL,
  name TEXT,
  UNIQUE (raid_id, board, party_index)
);

CREATE INDEX IF NOT EXISTS idx_raid_parties_raid ON raid_parties(raid_id);

-- Reusable "perma parties": fixed groups of up to 5 players, shared by every raid.
-- UNIQUE(player_id) keeps a player in at most one of them.
CREATE TABLE IF NOT EXISTS perma_parties (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT now_text(),
  updated_at TEXT NOT NULL DEFAULT now_text()
);

CREATE TABLE IF NOT EXISTS perma_party_members (
  perma_party_id BIGINT NOT NULL REFERENCES perma_parties(id) ON DELETE CASCADE,
  slot_index INTEGER NOT NULL,
  player_id BIGINT NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  PRIMARY KEY (perma_party_id, slot_index),
  UNIQUE (player_id)
);

-- One row per guild league fought, with the guild totals from the battle record.
CREATE TABLE IF NOT EXISTS guild_leagues (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date TEXT NOT NULL,
  result TEXT,
  participants INTEGER,
  total_kills BIGINT,
  towers INTEGER,
  created_at TEXT NOT NULL DEFAULT now_text()
);

-- Each roster player's battle-record line for a league. A player with no row for
-- a league didn't attend it. "ign" keeps the name exactly as the screenshot showed.
CREATE TABLE IF NOT EXISTS guild_league_stats (
  league_id BIGINT NOT NULL REFERENCES guild_leagues(id) ON DELETE CASCADE,
  player_id BIGINT NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  ign TEXT NOT NULL,
  kills BIGINT NOT NULL,
  assists BIGINT NOT NULL,
  player_damage BIGINT NOT NULL,
  building_damage BIGINT NOT NULL,
  PRIMARY KEY (league_id, player_id)
);

-- The app talks to Postgres directly as the database owner, never through
-- Supabase's public REST API. RLS with no policies keeps that API closed.
ALTER TABLE players ENABLE ROW LEVEL SECURITY;
ALTER TABLE raids ENABLE ROW LEVEL SECURITY;
ALTER TABLE raid_slots ENABLE ROW LEVEL SECURITY;
ALTER TABLE raid_parties ENABLE ROW LEVEL SECURITY;
ALTER TABLE perma_parties ENABLE ROW LEVEL SECURITY;
ALTER TABLE perma_party_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE guild_leagues ENABLE ROW LEVEL SECURITY;
ALTER TABLE guild_league_stats ENABLE ROW LEVEL SECURITY;
